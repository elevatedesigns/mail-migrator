"""Which Google and Microsoft app registrations the app signs in with.

Order of precedence for each value:
  1. An override the user typed in Settings (stored by the GUI, passed in here)
  2. An environment variable (handy for development)
  3. The IDs built into official releases (``_build_ids.py``, generated by
     build.py from CI secrets and never committed)
"""

from __future__ import annotations

import os
from dataclasses import dataclass

try:  # Present only in official builds.
    from . import _build_ids as _built  # type: ignore
except ImportError:  # pragma: no cover - depends on the build
    _built = None


ENV = {
    "google_client_id": "MAILMIGRATOR_GOOGLE_CLIENT_ID",
    "google_client_secret": "MAILMIGRATOR_GOOGLE_CLIENT_SECRET",
    "microsoft_client_id": "MAILMIGRATOR_MICROSOFT_CLIENT_ID",
    "microsoft_tenant": "MAILMIGRATOR_MICROSOFT_TENANT",
}


@dataclass
class AppIds:
    google_client_id: str = ""
    google_client_secret: str = ""   # Google "Desktop app" clients have a non-secret secret
    microsoft_client_id: str = ""
    microsoft_tenant: str = "common"  # "common" accepts work, school and personal accounts

    @property
    def has_google(self) -> bool:
        return bool(self.google_client_id)

    @property
    def has_microsoft(self) -> bool:
        return bool(self.microsoft_client_id)


def app_ids(overrides: dict | None = None) -> AppIds:
    overrides = overrides or {}
    ids = AppIds()
    for field in ("google_client_id", "google_client_secret", "microsoft_client_id",
                  "microsoft_tenant"):
        value = (overrides.get(field) or "").strip()
        if not value:
            value = os.environ.get(ENV[field], "").strip()
        if not value and _built is not None:
            value = str(getattr(_built, field.upper(), "") or "").strip()
        if value:
            setattr(ids, field, value)
    return ids


def builtin_ids_present() -> bool:
    return _built is not None and bool(getattr(_built, "GOOGLE_CLIENT_ID", "") or
                                       getattr(_built, "MICROSOFT_CLIENT_ID", ""))
